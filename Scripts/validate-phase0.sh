#!/bin/bash
# Runs the Phase 0 checks against build/Harmune.app and writes the evidence to
# docs/PHASE0_RESULTS.md. It plays music out loud and asks what you heard.
#
#   Scripts/validate-phase0.sh [search term]
#
# Quit Music.app first. This script never quits it for you.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1
TERM_QUERY="${1:-Radiohead}"
APP="${HARMUNE_HOST_APP:-$PWD/build/Harmune.app}"
CLI="$APP/Contents/Resources/bin/harmune"
LOG="$HOME/Library/Logs/Harmune/host.log"
OUT=docs/PHASE0_RESULTS.md
ROWS=""

[ -x "$CLI" ] || { echo "No CLI at $CLI. Run Scripts/build-host.sh first." >&2; exit 1; }
if pgrep -x Music >/dev/null; then
    echo "Music.app is running. Quit it and run this again, because V1 only means something with it closed." >&2
    exit 1
fi

record() { ROWS+="| $1 | $2 | $3 |"$'\n'; echo "  [$2] $1: $3"; }
field() { plutil -extract "$1" raw -o - - 2>/dev/null <<<"$2"; }
ask() {
    local answer
    read -r -p "  $1 [y/n] " answer
    case "$answer" in y|Y) return 0 ;; *) return 1 ;; esac
}

write_results() {
    local signer profile
    signer="$(codesign -dvv "$APP" 2>&1 | sed -n 's/^Authority=\([^:]*\).*/\1/p' | head -1)"
    [ -f "$APP/Contents/embedded.provisionprofile" ] && profile=yes || profile=no
    {
        echo "# Phase 0 results"
        echo
        echo "Generated by \`Scripts/validate-phase0.sh\` on $(date '+%Y-%m-%d %H:%M')."
        echo
        echo "- macOS: $(sw_vers -productVersion)"
        echo "- Signed with: ${signer:-ad hoc}"
        echo "- Provisioning profile embedded: $profile"
        echo "- Bundle ID: $(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$APP/Contents/Info.plist")"
        echo
        echo "| Check | Result | Evidence |"
        echo "|---|---|---|"
        printf '%s' "$ROWS"
        echo
        echo "## Manual checks still to record"
        echo
        echo "- **V2:** repeat this run with a Developer ID build, notarized and installed in /Applications."
        echo "- **V4:** start music from one terminal window, close that window, confirm it keeps playing, and run \`harmune status\` in a new window."
        echo "- **V5:** lock the screen for 10 minutes while playing."
        echo "- **V7:** check media keys and Now Playing in Control Center."
        echo
        echo "## Host log (last 40 lines)"
        echo
        echo '```'
        tail -40 "$LOG" 2>/dev/null
        echo '```'
    } > "$OUT"
    echo
    echo "Wrote $OUT"
}
trap write_results EXIT

echo "==> Starting the host through LaunchServices (V3)"
"$CLI" service stop --force >/dev/null 2>&1
sleep 1
if ! "$CLI" service start >/dev/null; then
    record "V3 hidden launch" FAIL "service start failed"
    exit 1
fi
STATUS="$("$CLI" service status --json)"
BACKEND="$(field backend "$STATUS")"
PID="$(field pid "$STATUS")"
if [ "$BACKEND" != musickit ]; then
    record "V3 hidden launch" FAIL "connected to the '$BACKEND' backend, not musickit"
    exit 1
fi
PPID_HOST="$(ps -o ppid= -p "$PID" | tr -d ' ')"
if [ "$PPID_HOST" = 1 ]; then
    record "V3 hidden launch" PASS "pid $PID, parent is launchd, so it isn't tied to this terminal"
else
    record "V3 hidden launch" FAIL "pid $PID has parent $PPID_HOST"
fi

echo "==> Requesting Apple Music access (V6)"
BEFORE="$(field state "$("$CLI" auth status --json)")"
AUTH="$(field state "$("$CLI" auth --json)")"
if [ "$BEFORE" = notDetermined ]; then
    if ask "Did the system prompt name Harmune, not your terminal?"; then
        record "V6 prompt names Harmune" PASS "confirmed by the person running this"
    else
        record "V6 prompt names Harmune" FAIL "reported by the person running this; state is now $AUTH"
    fi
else
    record "V6 prompt names Harmune" SKIP "already decided ($BEFORE). Reset with: tccutil reset MediaLibrary <bundle id>"
fi
if [ "$AUTH" != authorized ]; then
    record "Authorization" FAIL "state is $AUTH"
    exit 1
fi
record "Authorization" PASS "authorized, and the account can play catalog content"

echo "==> Searching the catalog for \"$TERM_QUERY\""
if ! SEARCH="$("$CLI" search "$TERM_QUERY" --json 2>&1)"; then
    record "Catalog search" FAIL "$SEARCH"
    exit 1
fi
SONG="$(field songs.0.id "$SEARCH")"
SECOND="$(field songs.1.id "$SEARCH")"
if [ -z "$SONG" ]; then
    record "Catalog search" FAIL "no songs returned"
    exit 1
fi
record "Catalog search" PASS "first song is $SONG, \"$(field songs.0.title "$SEARCH")\""

echo "==> Playing $SONG (V1)"
if ! PLAY="$("$CLI" play "$SONG" 2>&1)"; then
    record "V1 plays without Music.app" FAIL "$PLAY"
    echo "  Try the next step in docs/PHASE0_SETUP.md."
    exit 1
fi
sleep 2
P1="$(field position "$("$CLI" status --json)")"
sleep 10
P2="$(field position "$("$CLI" status --json)")"
ADVANCED="$(awk -v a="$P1" -v b="$P2" 'BEGIN { print (b - a > 5) ? "yes" : "no" }')"
MUSIC="$(pgrep -x Music || true)"
if [ "$ADVANCED" = yes ] && [ -z "$MUSIC" ] && ask "Can you hear the song?"; then
    record "V1 plays without Music.app" PASS "position went $P1 to $P2 s, Music.app stayed closed, audio heard"
else
    record "V1 plays without Music.app" FAIL "position $P1 to $P2 s; Music.app pid: ${MUSIC:-none}; see host log"
fi

echo "==> Checking the other APIs"
if [ -n "$SECOND" ] && "$CLI" add "$SECOND" --next >/dev/null 2>&1; then
    COUNT="$("$CLI" queue --json | plutil -extract entries raw -o - - 2>/dev/null)"
    record "V11 queue insert" PASS "queue has $COUNT entries after play next"
else
    record "V11 queue insert" FAIL "insert failed; see host log"
fi

"$CLI" pause >/dev/null 2>&1
sleep 1
if [ "$(field playing "$("$CLI" status --json)")" = false ]; then
    record "V12 state updates" PASS "status reported paused after pause"
else
    record "V12 state updates" FAIL "status didn't report paused"
fi

START="$(date +%s)"
if ALBUMS="$("$CLI" library albums --json 2>&1)"; then
    COUNT="$(plutil -extract items raw -o - - <<<"$ALBUMS" 2>/dev/null)"
    record "V8 library albums" PASS "${COUNT:-0} albums in the first page, $(( $(date +%s) - START )) s"
else
    record "V8 library albums" FAIL "$ALBUMS"
fi

sleep 3  # give artwork downloads a moment
SCHEMES="$(grep "can't download URL scheme" "$LOG" 2>/dev/null | sed 's/.*scheme //' | sort -u | tr '\n' ' ')"
FILES="$(ls "$HOME/Library/Caches/Harmune/artwork" 2>/dev/null | wc -l | tr -d ' ')"
record "V9 artwork" INFO "$FILES files cached; URL schemes it couldn't download: ${SCHEMES:-none}"

record "V10 home requests" INFO "open Home in the TUI, then look for 'home:' lines in $LOG"

echo
echo "Music is paused. Resume with: $CLI toggle"
